/*
 * Builds assets/js/class-book-icons.js from the SVG files of Font Awesome Free.
 *
 * Only the icons listed below are taken over, as path data. Font Awesome itself
 * (CSS, web fonts, JavaScript) is not part of the bundle. Run "npm run icons"
 * after changing the list and commit the result.
 */
const fs = require('fs');
const path = require('path');

// Name in the app => SVG file of Font Awesome Free (svgs/<style>/<name>.svg)
const ICONS = {
    'user': 'solid/user',
    'logout': 'solid/right-from-bracket',
    'security': 'solid/shield-halved',
    'moon': 'solid/moon',
    'sun': 'solid/sun',
    'copy': 'regular/copy',
    'pin': 'solid/thumbtack',
    'location': 'solid/location-dot',
    'close': 'solid/xmark',
    // Main navigation on small screens (off-canvas)
    'menu': 'solid/bars',
    'week': 'solid/calendar-week',
    'day': 'solid/calendar-day',
    'groups': 'solid/people-group',
    'seating': 'solid/chair',
    'settings': 'solid/gear',
};

const root = path.join(__dirname, '..', '..');
const source = path.join(root, 'node_modules', '@fortawesome', 'fontawesome-free');
const version = require(path.join(source, 'package.json')).version;
const icons = {};

Object.entries(ICONS).forEach(([name, file]) => {
    const svg = fs.readFileSync(path.join(source, 'svgs', file + '.svg'), 'utf8');
    const viewBox = /viewBox="([^"]+)"/.exec(svg);
    const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1]);

    if (!viewBox || 1 !== paths.length) {
        throw new Error('Unexpected SVG: ' + file);
    }

    icons[name] = {viewBox: viewBox[1], path: paths[0]};
});

const lines = [
    '/*!',
    ' * Icons: Font Awesome Free ' + version + ' by @fontawesome - https://fontawesome.com',
    ' * License - https://fontawesome.com/license/free (Icons: CC BY 4.0)',
    ' * Copyright Fonticons, Inc.',
    ' *',
    ' * Generated by tools/icons/build.js, do not edit.',
    ' */',
    'window.ClassBookIcons = ' + JSON.stringify(icons, null, 4) + ';',
    '',
];

fs.writeFileSync(path.join(root, 'assets', 'js', 'class-book-icons.js'), lines.join('\n'));

console.log(Object.keys(icons).length + ' icons written (Font Awesome Free ' + version + ')');
